import test from 'node:test';
import assert from 'node:assert/strict';
import {cpSync, existsSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync} from 'node:fs';
import {join, resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
import ts from 'typescript';

const root = resolve(process.cwd());
const metadata = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as {version: string};
const begin = '<!-- PUI_APP_VERSION_START -->', end = '<!-- PUI_APP_VERSION_END -->';

test('the packaged application contract links to immutable examples for its own package version', () => {
  const contract = readFileSync(join(root, 'APP.md'), 'utf8');
  assert.ok(contract.includes(begin) && contract.includes(end), 'The checked version block is required');
  const block = contract.slice(contract.indexOf(begin), contract.indexOf(end) + end.length);
  assert.ok(block.includes(`pith-ui@${metadata.version}`));
  for (const file of ['main.ts', 'index.html']) assert.ok(block.includes(`https://github.com/minifish-org/pith-ui/blob/v${metadata.version}/examples/application/${file}`), file);
  assert.doesNotMatch(contract, /\]\(\.\/examples\//, 'Example sources are not in the npm package');
});

test('the application API reference indexes every public application export with versioned source links', () => {
  const path = join(root, 'APP-API.md');
  assert.ok(existsSync(path), 'Application consumers need a complete bundled API index');
  const reference = readFileSync(path, 'utf8');
  const program = ts.createProgram([join(root, 'src/app/index.ts')], {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler, noEmit: true, strict: true, skipLibCheck: true});
  const entry = program.getSourceFile(join(root, 'src/app/index.ts'))!, checker = program.getTypeChecker();
  const symbols = checker.getExportsOfModule(checker.getSymbolAtLocation(entry)!);
  assert.ok(reference.includes(`pith-ui@${metadata.version}`));
  for (const symbol of symbols) assert.ok(reference.includes(`### ${symbol.name}\n`), symbol.name);
  const sourceLinks = [...reference.matchAll(/\[Source\]\(([^)]+)\)/g)].map(match => match[1]);
  assert.ok(sourceLinks.length >= symbols.length);
  assert.ok(sourceLinks.every(link => link.startsWith(`https://github.com/minifish-org/pith-ui/blob/v${metadata.version}/src/`)));
  assert.doesNotMatch(reference, /^### (?:createButton|createWorkspaceShell|createResourceEditor)$/m, 'General factories must not become application exports');
});

test('the existing docs command generates both APIs and rejects stale application links without writing in check mode', () => {
  const directory = mkdtempSync(join(tmpdir(), 'pui-app-docs-'));
  try {
    for (const path of ['src', 'showroom', 'scripts/api-docs.ts', 'docs/catalog.md', 'package.json', 'tsconfig.json', 'tsconfig.build.json', 'APP.md']) cpSync(join(root, path), join(directory, path), {recursive: true});
    symlinkSync(join(root, 'node_modules'), join(directory, 'node_modules'), 'dir');
    const run = (check = false) => spawnSync(process.execPath, ['scripts/api-docs.ts', ...(check ? ['--check'] : [])], {cwd: directory, encoding: 'utf8'});
    const generated = run(); assert.equal(generated.status, 0, generated.stderr || generated.stdout);
    assert.ok(existsSync(join(directory, 'API.md')), 'The original general reference stays generated');
    assert.ok(existsSync(join(directory, 'APP-API.md')), 'The application reference is generated by the same command');
    assert.ok(readFileSync(join(directory, 'APP.md'), 'utf8').includes(begin));
    const verified = run(true); assert.equal(verified.status, 0, verified.stderr || verified.stdout);
    const app = join(directory, 'APP.md'), previous = readFileSync(app, 'utf8');
    const stale = previous.replace(`/blob/v${metadata.version}/examples/application/main.ts`, '/blob/v0.0.0/examples/application/main.ts');
    assert.notEqual(stale, previous); writeFileSync(app, stale);
    const checked = run(true); assert.notEqual(checked.status, 0); assert.match(checked.stderr, /APP\.md.*out of date/i);
    assert.equal(readFileSync(app, 'utf8'), stale, '--check never rewrites application documentation');
    const repaired = run(); assert.equal(repaired.status, 0, repaired.stderr || repaired.stdout);
    const reference = join(directory, 'APP-API.md'), before = readFileSync(reference, 'utf8');
    writeFileSync(reference, before + '\nSTALE\n');
    const changed = run(true); assert.notEqual(changed.status, 0); assert.match(changed.stderr, /APP-API\.md.*out of date/i);
    assert.equal(readFileSync(reference, 'utf8'), before + '\nSTALE\n');
  } finally {rmSync(directory, {recursive: true, force: true});}
});
